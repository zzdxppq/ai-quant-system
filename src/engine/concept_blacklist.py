"""概念黑名单 — 屏蔽非题材性元标签

东财 `m:90+t:3` 概念板块里混入了大量"市场状态"和"持股资金属性"标签，
这些不构成真正的炒作主题，但因覆盖股数多，会污染概念热度排序，
把真正的题材（半导体/光刻机/商业航天 等）压到后排。

本模块在【聚合阶段】统一过滤，从源头把这些元标签从 ConceptHeat 列表移除。
若要恢复某项，把它从 META_CONCEPT_BLACKLIST 移除即可。
"""
import re

# 字面值黑名单 — 与东财概念名完全一致
META_CONCEPT_BLACKLIST: set[str] = {
    # ── 持股资金/通道类 ─────────────────────────
    "融资融券", "沪股通", "深股通", "陆股通",
    "QFII重仓", "QFII持股", "QFII概念", "机构重仓", "社保重仓",
    "基金重仓", "私募重仓",
    # ── 国际/国内指数纳入 ──────────────────────
    "MSCI概念", "MSCI中国", "富时罗素", "富时概念", "标准普尔",
    "深成500", "中证500", "中证1000", "中证100", "上证50",
    "沪深300", "深证100",
    # ── 风格分类 ───────────────────────────────
    "小盘成长", "小盘价值", "中盘成长", "中盘价值",
    "大盘成长", "大盘价值",
    # ── 价格区间 ───────────────────────────────
    "百元股", "低价股",
    # ── 市值规模 ───────────────────────────────
    "大盘股", "中盘股", "小盘股",
    # ── 板别 / 上市状态 ────────────────────────
    "创业板综", "科创板综", "深市次新", "沪市次新",
    "次新股", "次新开板",
    "AB股", "B股概念", "H股", "B股",
    # ── 行情元数据（昨日 / 近期价格行为）────────
    "百日新高", "近期新高", "百日新低", "近期新低",
    "历史新高", "历史新低", "新高", "新低",
    "昨日触板", "昨日涨停", "昨日炸板", "昨日跌停",
    "昨日涨停_含一字", "昨日首板", "昨日二板", "昨日三板",
    "昨日高振幅", "昨日高换手", "最近多板", "近期多板", "连续涨停",
    # ── 流动性 / 限制 ──────────────────────────
    "流通受限股", "已质押股权", "转债标的",
    # ── 通用市场行为 ───────────────────────────
    "东方财富热股", "破净股", "举牌概念",
    # ── 一些通用业绩特征 ───────────────────────
    "高送转", "高送转预期",
}

# 模式匹配：财报相关（带年份前缀的动态名称）
_PERF_KEYWORDS: tuple[str, ...] = (
    "年报预增", "年报预减", "年报扭亏", "年报预盈",
    "季报预增", "季报预减", "季报扭亏",
    "三季报预增", "三季报预减", "三季报扭亏",
    "中报预增", "中报预减", "中报扭亏",
    "业绩预增", "业绩预减", "业绩扭亏",
)

# 前缀规则：以这些字开头的概念几乎都是市场状态/行情元标签，不构成炒作主题
# 例："昨日XX" / "近期XX" / "最近XX" / "百日XX" / "今日XX" / "本周XX"
_META_PREFIXES: tuple[str, ...] = (
    "昨日", "近期", "最近", "百日", "今日", "本周", "本月", "前期",
)

# 年份前缀（如 "2025XXX" / "2026—XXX"）
_YEAR_PREFIX = re.compile(r"^20\d{2}[—\-－]?")


def is_meta_concept(name: str) -> bool:
    """是否为应屏蔽的元标签 / 非题材概念

    判定顺序：字面命中 → 前缀命中 → 财报关键字命中 → 年份模式 → 保留
    """
    if not name:
        return True
    if name in META_CONCEPT_BLACKLIST:
        return True
    for prefix in _META_PREFIXES:
        if name.startswith(prefix):
            return True
    for key in _PERF_KEYWORDS:
        if key in name:
            return True
    # 纯年份前缀的动态标签兜底（如 "2025...预增" 等已被 _PERF_KEYWORDS 覆盖；
    # 这里再处理 "2025...年" 这类不含财报关键词但本质也是年份元标签的）
    if _YEAR_PREFIX.match(name) and any(c in name for c in ("预", "扭亏", "高送", "新增", "公告")):
        return True
    return False


def filter_concepts(names: list[str]) -> list[str]:
    """过滤掉元标签，保留题材性概念，顺序不变"""
    return [n for n in names if not is_meta_concept(n)]
